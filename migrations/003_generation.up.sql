CREATE TABLE `generation_member_reviews` (
  `trip_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `member_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `conditions_version` int unsigned NOT NULL,
  `preference_version` int unsigned NOT NULL,
  `catalog_digest` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `source_fingerprint` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `normalization_digest` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `normalization_json` json NOT NULL,
  `review_json` json DEFAULT NULL,
  `review_version` int unsigned NOT NULL DEFAULT 0,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`trip_id`,`member_id`),
  CONSTRAINT `fk_generation_review_member` FOREIGN KEY (`trip_id`,`member_id`) REFERENCES `trip_members` (`trip_id`,`id`) ON DELETE CASCADE,
  CONSTRAINT `ck_generation_review_normalization` CHECK (JSON_TYPE(`normalization_json`) = 'OBJECT'),
  CONSTRAINT `ck_generation_review_review` CHECK (`review_json` IS NULL OR JSON_TYPE(`review_json`) = 'OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Private per-member generation normalization and review';

CREATE TABLE `generation_settings` (
  `trip_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `conditions_version` int unsigned NOT NULL,
  `settings_version` int unsigned NOT NULL DEFAULT 0,
  `settings_json` json NOT NULL,
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`trip_id`),
  CONSTRAINT `fk_generation_settings_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE,
  CONSTRAINT `ck_generation_settings_json` CHECK (JSON_TYPE(`settings_json`) = 'OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Generation window and owner-reviewed common fields';

CREATE TABLE `generation_jobs` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `trip_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `member_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `session_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `kind` varchar(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `method` varchar(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `path` varchar(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `idempotency_key` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `fingerprint` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `lease_token` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `lease_expires_at` datetime(3) NOT NULL,
  `status` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `phase` varchar(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `input_stamp_json` json NOT NULL,
  `response_json` json DEFAULT NULL,
  `plan_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `version_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `error_code` varchar(80) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `expires_at` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_generation_job_key` (`session_id`,`method`,`path`,`idempotency_key`),
  KEY `ix_generation_job_trip` (`trip_id`,`kind`,`status`,`created_at`),
  KEY `ix_generation_job_expiry` (`expires_at`),
  CONSTRAINT `fk_generation_job_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_generation_job_member` FOREIGN KEY (`trip_id`,`member_id`) REFERENCES `trip_members` (`trip_id`,`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_generation_job_session` FOREIGN KEY (`session_id`) REFERENCES `device_sessions` (`id`) ON DELETE CASCADE,
  CONSTRAINT `ck_generation_job_kind` CHECK (`kind` IN ('NORMALIZE_SELF','GENERATE','SAVE_PLAN')),
  CONSTRAINT `ck_generation_job_method` CHECK (`method` IN ('POST')),
  CONSTRAINT `ck_generation_job_status` CHECK (`status` IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','STALE')),
  CONSTRAINT `ck_generation_job_phase` CHECK (`phase` IN ('queued','normalizing','selecting','generating','validating','persisting','complete','failed')),
  CONSTRAINT `ck_generation_job_stamp` CHECK (JSON_TYPE(`input_stamp_json`) = 'OBJECT'),
  CONSTRAINT `ck_generation_job_response` CHECK (`response_json` IS NULL OR JSON_TYPE(`response_json`) IN ('OBJECT','ARRAY')),
  CONSTRAINT `ck_generation_job_expiry` CHECK (`expires_at` > `created_at`),
  CONSTRAINT `ck_generation_job_lease` CHECK (`lease_expires_at` > `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Generation API jobs, idempotency, and fenced leases';
