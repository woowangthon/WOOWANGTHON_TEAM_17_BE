CREATE TABLE `trip_canvas_documents` (
  `trip_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `revision` int unsigned NOT NULL DEFAULT 0,
  `schema_version` smallint unsigned NOT NULL DEFAULT 3,
  `document_json` json NOT NULL,
  `source_plan_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `source_version_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`trip_id`),
  CONSTRAINT `fk_trip_canvas_document_trip` FOREIGN KEY (`trip_id`) REFERENCES `trips` (`id`) ON DELETE CASCADE,
  CONSTRAINT `ck_trip_canvas_document_revision` CHECK (`revision` >= 0),
  CONSTRAINT `ck_trip_canvas_document_schema` CHECK (`schema_version` = 3),
  CONSTRAINT `ck_trip_canvas_document_json` CHECK (JSON_TYPE(`document_json`) = 'OBJECT'),
  CONSTRAINT `ck_trip_canvas_source_pair` CHECK ((`source_plan_id` IS NULL AND `source_version_id` IS NULL) OR (`source_plan_id` IS NOT NULL AND `source_version_id` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Shared canvas document per trip';

CREATE TABLE `trip_canvas_requests` (
  `session_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `trip_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `member_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `kind` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `method` varchar(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `path` varchar(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `idempotency_key` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `fingerprint` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `status` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `lease_token` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `lease_expires_at` datetime(3) DEFAULT NULL,
  `result_json` json DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `expires_at` datetime(3) NOT NULL,
  PRIMARY KEY (`session_id`,`method`,`path`,`idempotency_key`),
  KEY `ix_trip_canvas_requests_trip` (`trip_id`,`member_id`,`kind`,`created_at`),
  KEY `ix_trip_canvas_requests_expiry` (`expires_at`),
  CONSTRAINT `fk_trip_canvas_request_session` FOREIGN KEY (`session_id`) REFERENCES `device_sessions` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_trip_canvas_request_member` FOREIGN KEY (`trip_id`,`member_id`) REFERENCES `trip_members` (`trip_id`,`id`) ON DELETE CASCADE,
  CONSTRAINT `ck_trip_canvas_request_kind` CHECK (`kind` IN ('SAVE','RECOMMEND')),
  CONSTRAINT `ck_trip_canvas_request_method` CHECK (`method` IN ('PUT','POST')),
  CONSTRAINT `ck_trip_canvas_request_status` CHECK (`status` IN ('PENDING','COMPLETE')),
  CONSTRAINT `ck_trip_canvas_request_result` CHECK ((`status` = 'PENDING' AND `result_json` IS NULL) OR (`status` = 'COMPLETE' AND `result_json` IS NOT NULL)),
  CONSTRAINT `ck_trip_canvas_request_expiry` CHECK (`expires_at` > `created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Canvas save and recommendation idempotency leases';
